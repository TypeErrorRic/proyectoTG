class FrameCache:
    """Expose one in-memory RGB-D pair through the dataset loader API."""

    def __init__(self) -> None:
        self.rgb_bgr: Optional[np.ndarray] = None
        self.depth_m: Optional[np.ndarray] = None

    def set_frame(self, rgb_bgr: np.ndarray, depth_m: np.ndarray) -> None:
        self.rgb_bgr = rgb_bgr
        self.depth_m = depth_m

    def load(self, index=None):
        del index
        if self.rgb_bgr is None or self.depth_m is None:
            return None, None
        return self.rgb_bgr, self.depth_m


