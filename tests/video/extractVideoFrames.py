"""Segment synchronized RGB and raw RealSense depth image pairs.

Input generated by createHDF5.py:

    tests/video/videos/capture.h5

Before processing, RGB/, depth/, and capture_metadata.json are reconstructed
from the HDF5 file.

Output:

    tests/video/data/RGB/frame_000001.png
    tests/video/data/overlay/frame_000001.png
    tests/video/data/puerta/frame_000001.png
    tests/video/data/muro/frame_000001.png
    tests/video/data/camino_transitable/frame_000001.png
"""

